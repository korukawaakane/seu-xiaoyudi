import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src/data/generated-content.ts");
const collections = [
  ["projects", "Project"],
  ["people", "Person"],
  ["stories", "Story"],
  ["achievements", "Achievement"],
];

const imports = [];
const exports = [];

for (const [collection, typeName] of collections) {
  const directory = resolve(root, "src/content", collection);
  const files = (await readdir(directory))
    .filter((file) => file.endsWith(".json"))
    .sort((left, right) => left.localeCompare(right));
  const identifiers = [];

  for (const [index, file] of files.entries()) {
    const source = await readFile(resolve(directory, file), "utf8");
    const document = JSON.parse(source);
    if (!document || typeof document.id !== "string" || !document.id.trim()) {
      throw new Error(`${collection}/${file} must contain a non-empty id`);
    }

    const identifier = `${collection}Document${index}`;
    const importPath = relative(dirname(outputPath), resolve(directory, file))
      .split(sep)
      .join("/");
    imports.push(`import ${identifier} from "${importPath.startsWith(".") ? importPath : `./${importPath}`}";`);
    identifiers.push(`${identifier} as ${typeName}`);
  }

  const exportName = `generated${collection[0].toUpperCase()}${collection.slice(1)}`;
  exports.push(`export const ${exportName}: ${typeName}[] = [\n  ${identifiers.join(",\n  ")},\n];`);
}

const content = [
  "// Generated by scripts/generate-content-index.mjs. Do not edit manually.",
  'import type { Achievement, Person, Project, Story } from "@/src/types";',
  "",
  ...imports,
  "",
  ...exports.flatMap((entry) => [entry, ""]),
].join("\n");

await writeFile(outputPath, content, "utf8");
